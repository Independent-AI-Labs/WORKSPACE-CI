#!/usr/bin/env bash
# reinstall-hooks tests for the ownership-only consumer-hook policy.
# Sourced by run_tests_unit.sh; test_helpers.sh is already loaded.

_make_reinstall_fixture() {
    mkdir -p "$TEST_TMP/repo/.git/hooks" "$TEST_TMP/bin"
    git -C "$TEST_TMP/repo" init -q .
    printf '# AUTO-GENERATED by generate-hooks\n' > "$TEST_TMP/repo/.git/hooks/pre-commit"
    cat > "$TEST_TMP/repo/.pre-commit-config.yaml" <<'EOF'
repos:
  - repo: local
    hooks:
      - id: check-unstaged
        name: check-unstaged
        entry: "true"
        language: system
        stages: [pre-commit]
        pass_filenames: false
EOF
}

test_reinstall_unsealed_generates_hooks() {
    _make_reinstall_fixture
    (
        cd "$TEST_TMP/repo"
        bash "$PROJECT_DIR/scripts/reinstall-hooks"
    ) >/dev/null
    grep -q 'AUTO-GENERATED by' "$TEST_TMP/repo/.git/hooks/pre-commit"
}
_run_test "reinstall-hooks: ownership-only path generates hooks" test_reinstall_unsealed_generates_hooks
